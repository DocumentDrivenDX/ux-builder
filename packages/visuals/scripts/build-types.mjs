#!/usr/bin/env node
/* Write index.d.ts: the umf.visual types generated from the newest pinned schema (no hand copy,
   visuals PRD §6.3; each later version only adds to the one before), then the package API
   (CONTRACT-009).

     node scripts/build-types.mjs           write
     node scripts/build-types.mjs --check   fail when out of date */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = join(dirname(fileURLToPath(import.meta.url)), "..");
const pinned = JSON.parse(readFileSync(join(here, "schema/PINNED.json"), "utf8"));
const latest = pinned.versions.at(-1);
const schema = JSON.parse(readFileSync(join(here, `schema/umf-visual-${latest}.schema.json`), "utf8"));
const pascal = (s) => s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());
const NAMES = { id: "VisualId", labelled: "VisualLabelled" };
const typeName = (def) => NAMES[def] ?? `Visual${pascal(def)}`;

function ts(s, indent) {
  if (s.$ref) return typeName(s.$ref.split("/").at(-1));
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.oneOf) return s.oneOf.map((x) => ts(x, indent)).join(" | ");
  if (s.type === "array") return `${wrap(ts(s.items ?? {}, indent))}[]`;
  if (s.type === "object") {
    const req = new Set(s.required ?? []);
    const pad = "  ".repeat(indent + 1);
    const props = Object.entries(s.properties ?? {}).map(([k, v]) => `${pad}${/^[A-Za-z_]\w*$/.test(k) ? k : JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(v, indent + 1)};`);
    return `{\n${props.join("\n")}\n${"  ".repeat(indent)}}`;
  }
  if (s.type === "integer" || s.type === "number") return "number";
  if (s.type === "boolean") return "boolean";
  if (s.type === "string") return "string";
  return "unknown";
}
const wrap = (t) => (t.includes("|") ? `(${t})` : t);

const lines = [
  `// Generated by scripts/build-types.mjs from schema/umf-visual-${latest}.schema.json (umf-visual ${pinned.commit.slice(0, 12)}); do not edit.`,
  "",
  `// --- umf.visual ${latest} (umf-visual CONTRACT-083); the renderer also reads ${pinned.versions.slice(0, -1).join(", ")} ---`,
  "",
];
for (const [def, s] of Object.entries(schema.$defs)) lines.push(`export type ${typeName(def)} = ${ts(s, 0)};`, "");
const root = { ...schema };
delete root.$defs;
lines.push(`/** A umf.visual payload: the document-scope extension "umf.visual". */`, `export type Visual = ${ts(root, 0)};`, "");
lines.push(`export type VisualKind = Visual["kind"];`, `export type VisualForm = Visual["form"];`, "");
lines.push(readFileSync(join(here, "scripts/api.d.ts.txt"), "utf8").trimEnd(), "");
const text = lines.join("\n");
const out = join(here, "index.d.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) { console.error("index.d.ts is out of date: run npm run types --workspace @ux-builder/visuals"); process.exit(1); }
} else writeFileSync(out, text);
