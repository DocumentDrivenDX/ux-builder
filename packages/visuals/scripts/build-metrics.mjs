#!/usr/bin/env node
/* Extract text metrics from the fonts @ux-builder/tokens ships (ADR-042 decision 3): for each
   family and weight, the advance width of every covered character and the kerning of every
   printable ASCII pair, in font units. Rendering measures from metrics/fonts.json only, so it
   needs no font parser and gives the same widths in Node and in the browser.

     node scripts/build-metrics.mjs           write metrics/fonts.json
     node scripts/build-metrics.mjs --check   fail when it is out of date */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as fontkit from "fontkit";

const here = join(dirname(fileURLToPath(import.meta.url)), "..");
const fonts = join(dirname(createRequire(import.meta.url).resolve("@ux-builder/tokens/package.json")), "dist/fonts");
const OUT = join(here, "metrics/fonts.json");

// The characters a label can contain that we measure exactly; anything else falls back to the average advance.
const RANGES = [[0x20, 0x7e], [0xa0, 0x24f], [0x2010, 0x2027], [0x2030, 0x203a], [0x20ac, 0x20ac], [0x2190, 0x2193], [0x2192, 0x2192], [0x2212, 0x2212]];
const PRINTABLE = Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => String.fromCodePoint(0x20 + i));
// Families that are not body text: never a stand-in.
const NOT_BODY = /mono|fatface|slab/i;

function faces() {
  const out = [];
  for (const css of readdirSync(fonts).filter((f) => f.endsWith(".css"))) {
    for (const block of readFileSync(join(fonts, css), "utf8").matchAll(/@font-face\s*{([^}]*)}/g)) {
      const body = block[1];
      const family = /font-family:\s*'([^']+)'/.exec(body)?.[1];
      const weight = Number(/font-weight:\s*(\d+)/.exec(body)?.[1]);
      const file = /url\("\.\/([^"]+)"\)/.exec(body)?.[1];
      const ranges = (/unicode-range:\s*([^;]+);/.exec(body)?.[1] ?? "U+0000-10FFFF").split(",").map((r) => {
        const [a, b] = r.trim().slice(2).split("-");
        return [parseInt(a, 16), parseInt(b ?? a, 16)];
      });
      if (family && weight && file && !out.some((f) => f.file === file)) out.push({ family, weight, file, ranges });
    }
  }
  return out;
}

function extract() {
  const groups = new Map();
  for (const face of faces()) {
    const key = `${face.family}|${face.weight}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(face);
  }
  const families = {};
  for (const [key, list] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const [family, weight] = key.split("|");
    const opened = list.map((f) => ({ ...f, font: fontkit.openSync(join(fonts, f.file)) }));
    const em = opened[0].font.unitsPerEm;
    const fontFor = (cp) => opened.find((f) => f.ranges.some(([a, b]) => cp >= a && cp <= b))?.font;
    const advances = {};
    for (const [a, b] of RANGES) for (let cp = a; cp <= b; cp++) {
      const font = fontFor(cp);
      if (font?.hasGlyphForCodePoint(cp)) advances[cp.toString(16)] = Math.round((font.glyphForCodePoint(cp).advanceWidth * em) / font.unitsPerEm);
    }
    const latin = fontFor(0x41);
    const kern = {};
    for (const a of PRINTABLE) for (const b of PRINTABLE) {
      const pair = latin.layout(a + b).advanceWidth - latin.layout(a).advanceWidth - latin.layout(b).advanceWidth;
      if (pair) kern[a + b] = pair;
    }
    const values = Object.values(advances);
    (families[family] ??= {})[weight] = { em, average: Math.round(values.reduce((s, v) => s + v, 0) / values.length), advances, kern, files: list.map((f) => f.file).sort() };
  }
  // The stand-in for a theme whose font is not shipped: the widest body family, so text measured with it errs toward fitting.
  const sample = "The sign-in proxy forwards the agent's token with every request";
  const width = (m) => [...sample].reduce((s, c) => s + (m.advances[c.codePointAt(0).toString(16)] ?? m.average), 0) / m.em;
  const standIn = Object.entries(families).filter(([name, w]) => !NOT_BODY.test(name) && w[400])
    .sort(([a, x], [b, y]) => width(y[400]) - width(x[400]) || a.localeCompare(b))[0][0];
  return { $comment: "Generated by scripts/build-metrics.mjs from @ux-builder/tokens' fonts; do not edit.", standIn, families };
}

const text = JSON.stringify(extract()) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) { console.error("metrics/fonts.json is out of date: run npm run metrics --workspace @ux-builder/visuals"); process.exit(1); }
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${(text.length / 1024).toFixed(0)} kB)`);
}
