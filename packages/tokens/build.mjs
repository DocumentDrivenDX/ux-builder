/* Build @ux-builder/tokens from tokens/ at the repo root.

     npm run build

   Sources (ADR-013, ADR-018, CONTRACT-002): tokens/brands/*.brand.json,
   tokens/design-systems/*.design-system.json (shared: material, fluent,
   carbon), tokens/themes/*.theme.json and tokens/names.json (CONTRACT-001).
   Composition is in compose.mjs.

   Writes dist/ (CONTRACT-003):
     themes/<theme>.css       one theme, selected by data-theme (+ data-appearance)
     themes.css               every theme
     resolved/<theme>.<appearance>.json
                              every token's final value for one theme and
                              appearance: what the harness hands an embedded
                              view (ADR-011)
     manifest.json            themes, brands, shared design systems, preview pairs, every token name
     bridges/<surface>/<theme>.css
                              one theme mapped onto a generative UI library's
                              variables (shadcn, assistant-ui), contrast-checked
                              (bridges.mjs, ADR-023)
     fonts/<theme>.css        one theme's fonts, loaded by declared source (ADR-017)
     fonts.css                every bundled face of every theme
     fonts/*.woff2, *.LICENSE the bundled faces and their licences (fonts.mjs)
     brand/                   artwork the brand files point at
   and the preview surface, for tools that show any brand on any shared design
   system (the brand builder, the gallery); apps select themes, not these:
     brands/<brand>.css, design-systems/<design-system>.css
     resolved/<brand>.<design-system>.<appearance>.json

   Every theme and every preview pair is written whether or not an app uses
   it, so the contrast gate (tools/check-contrast.mjs) checks them all. */

import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { copyFonts, themeFontCss } from "./fonts.mjs";
import { SURFACES, bridgeCss, bridgeFailures } from "./bridges.mjs";
import { ComposeError, brandCss, combinations, defaultAppearance, designSystemCss, load, resolvedJson, resolvedPairJson, themeAppearances, themeCss } from "./compose.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
// --root and --out build another checkout's tokens/ and brand/ somewhere else:
// the end-to-end tests build the theme the theme builder just saved.
const { values: args } = parseArgs({ options: { root: { type: "string" }, out: { type: "string" } } });
const ROOT = args.root ? resolve(args.root) : join(HERE, "..", "..");
const DIST = args.out ? resolve(args.out) : join(HERE, "dist");
const HEADER = "/* Generated by @ux-builder/tokens from tokens/. Do not edit: change the theme, brand and design system files. */\n";
/* Artwork tokens are registered as URLs, so a relative url() resolves
   against the stylesheet that declares it (this one), not the one that draws
   it (ui.css, the app's CSS); unregistered, a page that links the CSS
   without a bundler would look for the artwork beside the wrong file. */
const ARTWORK = ["logo-image", "logo-mask", "mark-image", "mark-mask", "favicon"]
  .map((n) => `@property --piq-brand-${n} { syntax: "<url> | none"; inherits: true; initial-value: none; }`).join("\n") + "\n";

// Themes whose file also carries another theme, for apps that import the older file.
const ALSO_IN = {};

const guard = (fn) => {
  try { return fn(); } catch (e) {
    if (e instanceof ComposeError) { console.error(`build failed: ${e.message}`); process.exit(1); }
    throw e;
  }
};
const src = guard(() => load(join(ROOT, "tokens"), join(ROOT, "brand")));

rmSync(DIST, { recursive: true, force: true });
for (const d of ["themes", "resolved", "brands", "design-systems", "fonts", ...Object.keys(SURFACES).map((s) => `bridges/${s}`)]) mkdirSync(join(DIST, d), { recursive: true });
const write = (rel, text) => { writeFileSync(join(DIST, rel), text); console.log(`dist/${rel}`); };

guard(() => {
  const css = new Map([...src.themes.keys()].map((t) => [t, themeCss(src, t)]));
  for (const [t, c] of css) write(`themes/${t}.css`, HEADER + ARTWORK + "\n" + [c, ...(ALSO_IN[t] ?? []).map((o) => css.get(o))].join("\n"));
  // themes.css sits one folder above themes/, so its artwork paths lose a "../".
  write("themes.css", HEADER + ARTWORK + "\n" + [...css.values()].join("\n").replace(/url\("\.\.\/brand\//g, 'url("./brand/'));

  // Every token name any theme or preview pair sets: an embedded view resets the ones it is not given (ADR-011).
  const names = new Set();
  const bridgeProblems = [];
  for (const t of src.themes.values()) {
    const byAppearance = {};
    for (const ap of themeAppearances(src, t)) {
      const tokens = resolvedJson(src, t.name, ap);
      byAppearance[ap] = tokens;
      for (const k of Object.keys(tokens)) names.add(k);
      write(`resolved/${t.name}.${ap}.json`, JSON.stringify({ theme: t.name, appearance: ap, brand: t.brand, designSystem: t.designSystem ?? null, tokens }, null, 2) + "\n");
    }
    // Bridges: a library's pairings must pass as the SDK's own do; a failing bridge fails the build (ADR-023 rule 3).
    for (const surface of Object.keys(SURFACES)) {
      for (const [ap, tokens] of Object.entries(byAppearance)) {
        for (const f of bridgeFailures(tokens, surface)) bridgeProblems.push(`${t.name} ${ap}, ${surface} bridge: ${f.pair} is ${f.ratio ?? "unmeasurable"}:1, below ${f.floor}:1`);
      }
      writeFileSync(join(DIST, "bridges", surface, `${t.name}.css`), bridgeCss(t.name, byAppearance, defaultAppearance(src, t), surface));
    }
  }
  if (bridgeProblems.length) throw new ComposeError(`${bridgeProblems.length} bridge pairing${bridgeProblems.length > 1 ? "s" : ""} fail contrast:\n  ${bridgeProblems.join("\n  ")}`);
  console.log(`dist/bridges/<surface>/<theme>.css (${Object.keys(SURFACES).join(", ")} × ${src.themes.size} themes)`);

  for (const s of src.designSystems.keys()) write(`design-systems/${s}.css`, HEADER + "\n" + designSystemCss(src, s));
  for (const b of src.brands.keys()) write(`brands/${b}.css`, HEADER + ARTWORK + "\n" + brandCss(src, b));
  const pairs = combinations(src);
  for (const c of pairs) {
    const tokens = resolvedPairJson(src, c.brand, c.designSystem, c.appearance);
    for (const k of Object.keys(tokens)) names.add(k);
    writeFileSync(join(DIST, "resolved", `${c.brand}.${c.designSystem}.${c.appearance}.json`),
      JSON.stringify({ theme: `${c.brand}.${c.designSystem}`, preview: true, ...c, tokens }, null, 2) + "\n");
  }
  console.log(`dist/resolved/<brand>.<design-system>.<appearance>.json (${pairs.length} preview pairs)`);

  // Fonts: one file per theme, and every bundled face in one file for apps that offer every theme.
  const allFaces = new Set(), copies = [];
  for (const t of src.themes.values()) {
    const f = themeFontCss(src, t);
    write(`fonts/${t.name}.css`, f.css);
    copies.push(...f.copies);
    for (const face of f.css.match(/@font-face \{[\s\S]*?\}/g) ?? []) allFaces.add(face.replace(/url\("\.\//g, 'url("./fonts/'));
  }
  copyFonts(copies, join(DIST, "fonts"));
  write("fonts.css", "/* Every bundled font face of every theme (ADR-017). Browsers download only the faces a page uses. */\n" + [...allFaces].join("\n") + "\n");
  console.log(`dist/fonts/ (${new Set(copies.map((c) => c.file)).size} files)`);

  write("manifest.json", JSON.stringify({
    themes: [...src.themes.values()].map((t) => ({ name: t.name, title: t.title, brand: t.brand, designSystem: t.designSystem ?? null, default: defaultAppearance(src, t), appearances: themeAppearances(src, t) })),
    brands: [...src.brands.values()].map((b) => ({ name: b.name, title: b.title, appearances: Object.keys(b.appearances) })),
    designSystems: [...src.designSystems.values()].map((s) => ({ name: s.name, title: s.title, source: s.source })),
    previewPairs: pairs,
    tokens: [...names].sort(),
  }, null, 2) + "\n");
});

cpSync(join(ROOT, "brand"), join(DIST, "brand"), { recursive: true });
console.log("dist/brand/");
