const UNSAFE = /<script|\son\w+\s*=|\shref\s*=|<foreignObject|<image/i;
const round = (s) => s.replace(/-?\d+\.\d{3,}/g, (n) => String(Number(Number(n).toFixed(2))));

export function glyph(file) {
  const svg = readFileSync(resolve(LIB, file), "utf8").trim();
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const inner = /^<svg[^>]*>([\s\S]*)<\/svg>$/.exec(svg)?.[1];
  if (!viewBox || !inner || UNSAFE.test(svg) || !inner.includes('fill="#302A28"')) throw new Error(`${file} is not a library icon as expected`);
  const body = round(inner.replace(/\s*\n\s*/g, " ").replaceAll('fill="#302A28"', 'fill="currentColor"'));
  return { viewBox: viewBox.split(/\s+/).map((v) => String(Number(Number(v).toFixed(2)))).join(" "), body };
}

const files = () => readdirSync(LIB).filter((f) => /^s\d{2}-\d{3}\.svg$/.test(f)).sort();
const HEAD = `/* Generated by scripts/gen-synaptiq-icons.mjs from brand/synaptiq/icons/library (the Synaptiq brand icon library).
   Do not edit: run node scripts/gen-synaptiq-icons.mjs in packages/ui. */\n`;
const SET = { package: "brand/synaptiq/icons", version: "2026-11-19", license: "Synaptiq brand asset", svg: { fill: "currentColor" } };

export function renderShared() {
  const lines = Object.entries(SHARED).map(([name, [num, what]]) => `  // ${num}: ${what}\n  ${JSON.stringify(name)}: ${JSON.stringify(glyph(`s${num}.svg`))},`);
  return `${HEAD}
export const SYNAPTIQ_SET = ${JSON.stringify(SET)};

export const SYNAPTIQ_SHARED = {
${lines.join("\n")}
};
`;
}

export function renderLibrary() {
  const lines = files().map((f) => `  ${JSON.stringify(`syn-${f.slice(1, 7)}`)}: ${JSON.stringify(glyph(f))},`);
  return `${HEAD}
/* Every icon of the library by its number in the brand deck, syn-NN-MMM (${lines.length} icons). */
export const SYNAPTIQ_LIBRARY = {
${lines.join("\n")}
};
`;
}

const check = process.argv.includes("--check");
const outputs = [[OUT_SHARED, renderShared()], [OUT_LIBRARY, renderLibrary()]];
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  let stale = 0;
  for (const [path, text] of outputs) {
    if (check) { if (readFileSync(path, "utf8") !== text) { stale++; console.log(`out of date: ${path}`); } }
    else { writeFileSync(path, text); console.log(`wrote ${path} (${(text.length / 1024).toFixed(0)} KB)`); }
  }
  if (check) { console.log(stale ? "synaptiq icons: run node scripts/gen-synaptiq-icons.mjs" : "synaptiq icons: up to date"); process.exit(stale ? 1 : 0); }
}
