import { useCallback, useEffect, useId, useLayoutEffect, useMemo, useRef, useState } from "react";
import { Button } from "../widgets/Button.jsx";
import { TextArea } from "../widgets/Field.jsx";
import { Sheet } from "../widgets/Sheet.jsx";
import { Icon } from "../icons/Icon.jsx";
import { sizeAtLeast, useSizeClass } from "../patterns/Regions.jsx";
import { Markdown, plainText } from "./Markdown.jsx";
import { ApprovalCard, Reasoning, Sources, ToolCalls } from "./Parts.jsx";
import { GenerativeComponent } from "./Generative.jsx";

/* The words the conversation uses; pass strings to change any of them. */
const STRINGS = {
  you: "You",
  assistant: "Assistant",
  replying: "Replying…",
  stopped: "Stopped",
  failed: "The assistant could not reply.",
  retry: "Retry",
  regenerate: "Regenerate",
  stop: "Stop",
  send: "Send",
  busy: "Wait for the reply to finish, or stop it.",
  suggestions: "Suggestions",
  jump: "Jump to latest",
  open: "Open",
  close: "Close",
  replied: "Assistant replied:",
  approvalNeeded: "Approval needed:",
  approved: "Approved:",
  denied: "Denied:",
  actorAgent: "The assistant is working.",
  actorUser: "You are in control.",
};
const DISCLOSURE = "Replies are generated by AI and may be wrong. Check them before you rely on them.";

const partsOf = (m) => (m.parts?.length ? m.parts : m.text != null ? [{ type: "text", text: m.text }] : []);
const textOf = (m) => partsOf(m).filter((p) => p.type === "text").map((p) => p.text).join("\n\n");
const componentKey = (part, i) => part.id ?? `${part.component}-${i}`;

/* Runs of consecutive tool calls are one plan; everything else stays in its place. */
function group(parts) {
  const out = [];
  for (const p of parts) {
    if (p.type === "tool" && out.at(-1)?.type === "tools") out.at(-1).calls.push(p);
    else if (p.type === "tool") out.push({ type: "tools", calls: [p] });
    else out.push(p);
  }
  return out;
}

/* The latest approval request for each action, in conversation order: only it can be approved. */
function latestRequests(messages) {
  const latest = new Map();
  for (const m of messages) for (const p of partsOf(m)) if (p.type === "approval") latest.set(p.action ?? p.id, p.id);
  return latest;
}

/* A conversation with an assistant: the messages as a log, a composer, Stop
   while a reply streams, Retry when one fails, suggestions, and each reply's
   reasoning, tool calls, sources, approvals, artifacts and generated
   components. Finished replies are announced once each, never token by
   token. The app owns the messages and the runtime; this shows what it is
   given and reports what the user does. */
export function Conversation({
  messages = [], onSend, onStop, onRetry, onRegenerate, suggestions = [], onDecide, decisions, onComponentSubmit, renderArtifact,
  disabledReason, actor, label = "Conversation with the assistant", composerLabel = "Ask the assistant", disclosure = DISCLOSURE, strings, className,
}) {
  const s = { ...STRINGS, ...strings };
  const uid = useId();
  const root = useRef(null), log = useRef(null), field = useRef(null), opener = useRef(null), paneHeading = useRef(null);
  const size = useSizeClass(root);
  const [draft, setDraft] = useState("");
  const [announcement, setAnnouncement] = useState("");
  const [own, setOwn] = useState({});
  const [inputs, setInputs] = useState({});
  const [submitted, setSubmitted] = useState({});
  const [artifact, setArtifact] = useState(null);
  const [atBottom, setAtBottom] = useState(true);
  const bottom = useRef(true);

  const streaming = messages.some((m) => m.role === "assistant" && m.status === "streaming");
  const blocked = disabledReason || (streaming ? s.busy : null);
  const decided = { ...decisions, ...own };
  const latest = useMemo(() => latestRequests(messages), [messages]);

  // Announce each reply once as it finishes, and each approval request as it arrives; never what was there at first.
  const seen = useRef(null);
  useEffect(() => {
    const done = new Set(), asked = new Set();
    for (const m of messages) {
      if (m.role === "assistant" && (m.status ?? "done") !== "streaming") done.add(m.id);
      for (const p of partsOf(m)) if (p.type === "approval") asked.add(p.id);
    }
    if (seen.current) {
      const said = [];
      for (const m of messages) {
        if (done.has(m.id) && !seen.current.done.has(m.id)) {
          if (m.status === "error") said.push(m.error ?? s.failed);
          else said.push(`${s.replied} ${plainText(textOf(m))}${m.status === "stopped" ? ` (${s.stopped})` : ""}`);
        }
        for (const p of partsOf(m)) if (p.type === "approval" && !seen.current.asked.has(p.id)) said.push(`${s.approvalNeeded} ${p.summary}`);
      }
      if (said.length) setAnnouncement(said.join(" "));
    }
    seen.current = { done, asked };
  }, [messages, s.replied, s.stopped, s.failed, s.approvalNeeded]);

  // The newest message stays in view, unless the user has scrolled up.
  useLayoutEffect(() => {
    const el = log.current;
    if (el && bottom.current) el.scrollTop = el.scrollHeight;
  }, [messages]);
  const onScroll = () => {
    const el = log.current;
    const now = el.scrollHeight - el.scrollTop - el.clientHeight < 16;
    bottom.current = now;
    setAtBottom(now);
  };
  const jump = () => { const el = log.current; el.scrollTop = el.scrollHeight; bottom.current = true; setAtBottom(true); field.current?.focus(); };

  const send = (text) => {
    const t = text.trim();
    if (!t || blocked) return false;
    bottom.current = true;
    onSend?.(t);
    return true;
  };
  const submitDraft = () => { if (send(draft)) setDraft(""); field.current?.focus(); };
  const onKeyDown = (e) => {
    if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) { e.preventDefault(); submitDraft(); }
  };
  const stop = () => { onStop?.(); field.current?.focus(); };

  const decide = useCallback((m, p, decision) => {
    // Only the latest request for an action, not yet decided, can be decided; and only here.
    if (latest.get(p.action ?? p.id) !== p.id || p.current === false || decided[p.id]) return;
    setOwn((o) => ({ ...o, [p.id]: decision }));
    setAnnouncement(`${decision === "approved" ? s.approved : s.denied} ${p.summary}`);
    onDecide?.({ id: p.id, action: p.action ?? p.id, decision, messageId: m.id });
  }, [latest, decided, onDecide, s.approved, s.denied]);

  const openArtifact = (m, p, e) => { opener.current = e.currentTarget; setArtifact({ messageId: m.id, ...p }); };
  const closeArtifact = () => { setArtifact(null); requestAnimationFrame(() => opener.current?.focus()); };
  const beside = artifact && sizeAtLeast(size, "expanded");
  useEffect(() => { if (beside) paneHeading.current?.focus(); }, [beside, artifact?.id]);

  const disclosureId = `${uid}-ai`, fieldId = `${uid}-field`;

  function renderPart(m, p, i, ctx) {
    if (p.type === "text") return <Markdown key={i} text={p.text} sources={ctx.sources} idPrefix={ctx.prefix} />;
    if (p.type === "reasoning") return <Reasoning key={i} text={p.text} seconds={p.seconds} />;
    if (p.type === "tools") return <ToolCalls key={i} calls={p.calls} />;
    if (p.type === "sources") return ctx.firstSources === p ? <Sources key={i} sources={ctx.sources} idPrefix={ctx.prefix} /> : null;
    if (p.type === "approval") {
      const current = latest.get(p.action ?? p.id) === p.id && p.current !== false;
      return <ApprovalCard key={i} summary={p.summary} details={p.details} decision={decided[p.id]} current={current} onDecide={(d) => decide(m, p, d)} />;
    }
    if (p.type === "component") {
      const k = `${m.id}:${componentKey(p, ctx.componentIndex.get(p))}`;
      return (
        <GenerativeComponent key={i} component={p.component} props={p.props} values={inputs[k]} submitted={submitted[k] ?? p.submitted}
          onValuesChange={(v) => setInputs((x) => ({ ...x, [k]: v }))}
          onSubmit={(values) => { setSubmitted((x) => ({ ...x, [k]: values })); onComponentSubmit?.({ messageId: m.id, partId: componentKey(p, ctx.componentIndex.get(p)), component: p.component, values }); }} />
      );
    }
    if (p.type === "artifact") {
      return (
        <div key={i} className="piq-artifact-link">
          <Icon name="view" /><span className="piq-artifact-link__title">{p.title}</span>
          <Button size="sm" variant="secondary" aria-label={`${s.open} ${p.title}`} onClick={(e) => openArtifact(m, p, e)}>{s.open}</Button>
        </div>
      );
    }
    return null;
  }

  function renderMessage(m) {
    const status = m.role === "assistant" ? m.status ?? "done" : "done";
    if (m.role !== "assistant") {
      return (
        <li key={m.id} className="piq-message" data-role="user">
          <p className="piq-message__author">{s.you}</p>
          <div className="piq-message__content"><p className="piq-message__text">{textOf(m)}</p></div>
        </li>
      );
    }
    const parts = partsOf(m);
    const sources = parts.filter((p) => p.type === "sources").flatMap((p) => p.sources ?? []);
    const componentIndex = new Map(parts.filter((p) => p.type === "component").map((p, i) => [p, i]));
    const ctx = { sources, prefix: `${uid}-${m.id}-src`, firstSources: parts.find((p) => p.type === "sources"), componentIndex };
    return (
      <li key={m.id} className="piq-message" data-role="assistant" data-status={status} aria-busy={status === "streaming" || undefined}>
        <p className="piq-message__author">{s.assistant}</p>
        <div className="piq-message__content" data-piq-ai="generated" aria-describedby={disclosureId}>
          {group(parts).map((p, i) => renderPart(m, p, i, ctx))}
        </div>
        {status === "streaming" && <p className="piq-message__state">{s.replying}</p>}
        {status === "stopped" && <p className="piq-message__state">{s.stopped}</p>}
        {status === "error" && (
          <div className="piq-message__error">
            <p className="piq-message__state" data-tone="error"><Icon name="error" />{m.error ?? s.failed}</p>
            <Button size="sm" variant="secondary" data-piq-ai-control="retry" onClick={() => onRetry?.(m.id)}><Icon name="refresh" />{s.retry}</Button>
          </div>
        )}
        {(status === "done" || status === "stopped") && onRegenerate && (
          <div className="piq-message__actions">
            <Button size="sm" variant="text" data-piq-ai-control="regenerate" onClick={() => onRegenerate(m.id)}><Icon name="refresh" />{s.regenerate}</Button>
          </div>
        )}
      </li>
    );
  }

  const pane = artifact && (renderArtifact ? renderArtifact(artifact) : <Markdown text={artifact.content ?? ""} />);
  const items = suggestions.map((x) => (typeof x === "string" ? { label: x, prompt: x } : x));

  return (
    <div ref={root} className={`piq-conversation${className ? ` ${className}` : ""}`} data-piq-ai-label="" data-size={size} data-artifact={beside ? "open" : undefined}>
      <div className="piq-conversation__main">
        <p id={disclosureId} className="piq-conversation__disclosure"><Icon name="info" />{disclosure}</p>
        {actor && <p className="piq-conversation__actor" data-piq-ai-actor={actor} aria-live="polite">{actor === "agent" ? s.actorAgent : s.actorUser}</p>}
        <div ref={log} className="piq-conversation__log" role="log" aria-live="off" aria-label={label} tabIndex={0} onScroll={onScroll}>
          <ol className="piq-conversation__messages">{messages.map(renderMessage)}</ol>
        </div>
        {!atBottom && <Button className="piq-conversation__jump" size="sm" variant="secondary" onClick={jump}><Icon name="chevron-down" />{s.jump}</Button>}
        <p className="piq-visually-hidden" aria-live="polite" data-announcer="">{announcement}</p>
        {items.length > 0 && (
          <ul className="piq-conversation__suggestions" aria-label={s.suggestions}>
            {items.map((it) => <li key={it.label}><Button size="sm" variant="secondary" disabled={Boolean(blocked)} onClick={() => { send(it.prompt); field.current?.focus(); }}>{it.label}</Button></li>)}
          </ul>
        )}
        <form className="piq-composer" onSubmit={(e) => { e.preventDefault(); submitDraft(); }}>
          <TextArea ref={field} label={composerLabel} rows={2} value={draft} onChange={(e) => setDraft(e.target.value)} onKeyDown={onKeyDown}
            hint={blocked || undefined} id={fieldId} className="piq-composer__field" />
          <div className="piq-composer__actions">
            <p className="piq-composer__status" data-piq-ai="status" role="status" aria-live="polite" aria-busy={streaming ? "true" : "false"}>{streaming ? s.replying : ""}</p>
            {streaming && <Button variant="secondary" onClick={stop}>{s.stop}</Button>}
            <Button type="submit" disabled={Boolean(blocked) || !draft.trim()}>{s.send}</Button>
          </div>
        </form>
      </div>
      {beside && (
        <section className="piq-conversation__artifact" aria-labelledby={`${uid}-art`}>
          <div className="piq-conversation__artifact-head">
            <h2 id={`${uid}-art`} ref={paneHeading} tabIndex={-1} className="piq-conversation__artifact-title">{artifact.title}</h2>
            <Button variant="text" aria-label={`${s.close} ${artifact.title}`} onClick={closeArtifact}><Icon name="close" /></Button>
          </div>
          <div className="piq-conversation__artifact-body">{pane}</div>
        </section>
      )}
      {artifact && !beside && (
        <Sheet open side="full" title={artifact.title} onClose={closeArtifact} closeLabel={`${s.close} ${artifact.title}`}>
          <div className="piq-conversation__artifact-body">{pane}</div>
        </Sheet>
      )}
    </div>
  );
}

/* The assistant beside the page: from the expanded size class a side panel
   region next to children, below it a full-screen modal sheet. Focus moves
   into the panel's composer when it opens. panel is the Conversation. */
export function AssistantPanel({ open = false, onClose, title = "Assistant", panel, closeLabel = "Close assistant", children, className }) {
  const root = useRef(null), side = useRef(null);
  const size = useSizeClass(root);
  const wide = sizeAtLeast(size, "expanded");
  const id = useId();
  // When the user opens it, focus moves to its composer; a panel that starts open takes no focus.
  const was = useRef(open);
  useEffect(() => {
    const opened = open && !was.current;
    was.current = open;
    if (!opened) return;
    const el = side.current ?? root.current?.querySelector(".piq-sheet[open]");
    (el?.querySelector("textarea") ?? el)?.focus?.();
  }, [open]);
  return (
    <div ref={root} className={`piq-assistant-panel${className ? ` ${className}` : ""}`} data-open={open && wide ? "" : undefined} data-size={size}>
      <div className="piq-assistant-panel__page">{children}</div>
      {open && wide && (
        <aside ref={side} className="piq-assistant-panel__side" aria-labelledby={`${id}-t`}>
          <div className="piq-assistant-panel__head">
            <h2 id={`${id}-t`} className="piq-assistant-panel__title">{title}</h2>
            <Button variant="text" aria-label={closeLabel} onClick={() => onClose?.()}><Icon name="close" /></Button>
          </div>
          <div className="piq-assistant-panel__body">{panel}</div>
        </aside>
      )}
      {!wide && (
        <Sheet open={open} side="full" title={title} onClose={onClose} closeLabel={closeLabel} className="piq-assistant-panel__sheet">
          <div className="piq-assistant-panel__body">{panel}</div>
        </Sheet>
      )}
    </div>
  );
}
